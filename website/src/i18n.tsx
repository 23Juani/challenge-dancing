export const DICCIONARIOS: Record<Lang, Dict> = { es, en };
export type { Dict };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: Dict };
const LangContext = createContext<Ctx>({ lang: "es", setLang: () => {}, t: es });

function idiomaInicial(): Lang {
  try {
    const guardado = localStorage.getItem("bennett-lang");
    if (guardado === "es" || guardado === "en") return guardado;
  } catch {
    /* almacenamiento no disponible */
  }
  return "es";
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(idiomaInicial);
  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem("bennett-lang", lang);
    } catch {
      /* ignorar */
    }
  }, [lang]);
  return <LangContext.Provider value={{ lang, setLang, t: DICCIONARIOS[lang] }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);

export function fecha(ms: number | string, lang: Lang, largo = false) {
  const d = new Date(ms);
  if (Number.isNaN(d.getTime())) return String(ms);
  return d.toLocaleDateString(lang === "es" ? "es-BO" : "en-GB", {
    day: "2-digit",
    month: "short",
    ...(largo ? { year: "numeric" } : {}),
    timeZone: "UTC",
  });
}
export function num(v: number, lang: Lang, dec = 1) {
  return v.toLocaleString(lang === "es" ? "es-BO" : "en-US", { minimumFractionDigits: dec, maximumFractionDigits: dec });
}
